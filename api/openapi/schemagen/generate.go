// Package schemagen synchronizes the native REST contract from the shared catalogue.
package schemagen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/fatballfish/pic-gallery/internal/service/openplatform"
	"gopkg.in/yaml.v3"
)

// Schemas returns a deterministic, self-contained JSON Schema document. References
// emitted by ForType are relative to each operation, not the combined document.
func Schemas() ([]byte, error) {
	defs := map[string]any{}
	for _, s := range openplatform.Specs() {
		for suffix, schema := range map[string]map[string]any{"Input": s.InputSchema, "Output": s.OutputSchema} {
			name := s.Name + suffix
			rebase(schema, "#/$defs/"+name)
			defs[name] = schema
		}
	}
	raw, err := json.MarshalIndent(map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$comment": "Generated by go run ./api/openapi/cmd/generate; DO NOT EDIT.", "$defs": defs}, "", "  ")
	return append(raw, '\n'), err
}
func rebase(v any, base string) {
	switch x := v.(type) {
	case map[string]any:
		if ref, ok := x["$ref"].(string); ok && strings.HasPrefix(ref, "#") {
			x["$ref"] = base + strings.TrimPrefix(ref, "#")
		}
		for _, child := range x {
			rebase(child, base)
		}
	case []any:
		for _, child := range x {
			rebase(child, base)
		}
	}
}
func obj(props map[string]any, required ...string) map[string]any {
	m := map[string]any{"type": "object", "properties": props, "additionalProperties": false}
	if len(required) > 0 {
		m["required"] = required
	}
	return m
}
func ref(s string) map[string]any { return map[string]any{"$ref": s} }
func response(schema any) map[string]any {
	return map[string]any{"description": "Successful response", "content": map[string]any{"application/json": map[string]any{"schema": schema}}}
}
func envelope(schema any) map[string]any {
	return obj(map[string]any{"data": schema, "meta": map[string]any{"type": "object", "properties": map[string]any{"request_id": map[string]any{"type": "string"}}, "required": []string{"request_id"}}}, "data", "meta")
}
func node(v any) *yaml.Node {
	raw, _ := yaml.Marshal(v)
	var n yaml.Node
	_ = yaml.Unmarshal(raw, &n)
	return n.Content[0]
}
func get(n *yaml.Node, key string) *yaml.Node {
	for i := 0; i < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			return n.Content[i+1]
		}
	}
	return nil
}
func set(n *yaml.Node, key string, v any) {
	for i := 0; i < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			n.Content[i+1] = node(v)
			return
		}
	}
	n.Content = append(n.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: key}, node(v))
}
func remove(n *yaml.Node, key string) {
	for i := 0; i < len(n.Content); i += 2 {
		if n.Content[i].Value == key {
			n.Content = append(n.Content[:i], n.Content[i+2:]...)
			return
		}
	}
}
func decode(n *yaml.Node) map[string]any {
	m := map[string]any{}
	if n != nil {
		_ = n.Decode(&m)
	}
	return m
}

// Sync updates only catalogue operations and the four existing native request
// components. Other browser/admin contracts retain their source bytes.
func Sync(raw []byte) ([]byte, error) {
	var doc yaml.Node
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		return nil, err
	}
	root := doc.Content[0]
	paths := get(root, "paths")
	specs := map[string]openplatform.OperationSpec{}
	for _, s := range openplatform.Specs() {
		specs[s.Name] = s
	}
	type patch struct {
		start, end int
		text       string
	}
	patches := []patch{}
	lines := strings.Split(string(raw), "\n")
	addPatch := func(n *yaml.Node, end, indent int) error {
		var b bytes.Buffer
		e := yaml.NewEncoder(&b)
		e.SetIndent(2)
		if err := e.Encode(n); err != nil {
			return err
		}
		_ = e.Close()
		encoded := strings.TrimSuffix(b.String(), "\n")
		parts := strings.Split(encoded, "\n")
		for i := range parts {
			parts[i] = strings.Repeat(" ", indent) + parts[i]
		}
		patches = append(patches, patch{n.Line - 1, end, strings.Join(parts, "\n")})
		return nil
	}
	for p := 0; p < len(paths.Content); p += 2 {
		path := paths.Content[p].Value
		methods := paths.Content[p+1]
		if !strings.HasPrefix(path, "/api/open/v1/") {
			continue
		}
		for j := 0; j < len(methods.Content); j += 2 {
			method := methods.Content[j].Value
			op := methods.Content[j+1]
			id := get(op, "operationId")
			if id == nil {
				continue
			}
			s, ok := specs[id.Value]
			if !ok {
				continue
			}
			props := s.InputSchema["properties"].(map[string]any)
			required := map[string]bool{}
			switch r := s.InputSchema["required"].(type) {
			case []string:
				for _, k := range r {
					required[k] = true
				}
			case []any:
				for _, k := range r {
					required[k.(string)] = true
				}
			}
			params := []any{}
			used := map[string]bool{}
			if existing := get(op, "parameters"); existing != nil {
				for _, pn := range existing.Content {
					v := decode(pn)
					if v["in"] != "path" {
						continue
					}
					name, _ := v["name"].(string)
					key := name
					if name != "part_number" && name != "task_id" && name != "image_id" {
						key = "id"
					}
					if name == "task_id" && !strings.Contains(s.Name, "result_access") {
						key = "id"
					}
					if name == "asset_id" && strings.Contains(s.Name, "result_access") {
						key = "asset_id"
					}
					schema := props[key]
					if schema == nil {
						schema = map[string]any{"type": "string"}
					}
					v["schema"] = schema
					params = append(params, v)
					used[key] = true
				}
			}
			keys := []string{}
			for key := range props {
				keys = append(keys, key)
			}
			sort.Strings(keys)
			body := map[string]any{}
			bodyRequired := []string{}
			for _, key := range keys {
				if used[key] {
					continue
				}
				if method == "get" || method == "delete" {
					params = append(params, map[string]any{"name": key, "in": "query", "required": required[key], "schema": props[key]})
				} else {
					body[key] = props[key]
					if required[key] {
						bodyRequired = append(bodyRequired, key)
					}
				}
			}
			if _, ok := props["idempotency_key"]; ok {
				params = append(params, map[string]any{"name": "Idempotency-Key", "in": "header", "required": false, "description": "Overrides idempotency_key in JSON/query when supplied.", "schema": props["idempotency_key"]})
			}
			if len(params) > 0 {
				set(op, "parameters", params)
			} else {
				remove(op, "parameters")
			}
			if len(body) > 0 {
				set(op, "requestBody", map[string]any{"required": len(bodyRequired) > 0, "content": map[string]any{"application/json": map[string]any{"schema": obj(body, bodyRequired...)}}})
			} else {
				remove(op, "requestBody")
			}
			responses := decode(get(op, "responses"))
			delete(responses, "200")
			delete(responses, "201")
			status := "200"
			if strings.HasPrefix(s.Name, "create_") {
				status = "201"
			}
			responses[status] = response(envelope(ref("./components/schemas/native.generated.json#/$defs/" + s.Name + "Output")))
			for _, code := range []string{"400", "401", "403", "404", "409", "429", "500", "503"} {
				if _, ok := responses[code]; !ok {
					responses[code] = map[string]any{"description": "Native API error; see error.code and meta.request_id.", "content": map[string]any{"application/json": map[string]any{"schema": ref("./components/error-components.yaml#/components/schemas/ErrorResponse")}}}
				}
			}
			set(op, "responses", responses)
			end := len(lines) - 1
			if j+2 < len(methods.Content) {
				end = methods.Content[j+2].Line - 1
			} else if p+2 < len(paths.Content) {
				end = paths.Content[p+2].Line - 1
			} else {
				end = get(root, "components").Line - 2
			}
			if err := addPatch(op, end, 6); err != nil {
				return nil, err
			}
			delete(specs, s.Name)
		}
	}
	if len(specs) > 0 {
		return nil, fmt.Errorf("catalogue operations missing from OpenAPI: %v", specs)
	}
	schemas := get(get(root, "components"), "schemas")
	names := map[string]string{"DeveloperImagePreflightRequest": "preflight_image_task", "DeveloperImageCreateRequest": "create_image_task", "DeveloperVideoPreflightRequest": "preflight_video_task", "DeveloperVideoCreateRequest": "create_video_task"}
	for i := 0; i < len(schemas.Content); i += 2 {
		if schemas.Content[i].Value == "OAuthTokenResponse" {
			old := schemas.Content[i+1]
			value := decode(old)
			for _, key := range []string{"access_token", "refresh_token"} {
				delete(value["properties"].(map[string]any)[key].(map[string]any), "writeOnly")
			}
			n := node(value)
			n.Line = old.Line
			if err := addPatch(n, schemas.Content[i+2].Line-1, 6); err != nil {
				return nil, err
			}
		}
		if name, ok := names[schemas.Content[i].Value]; ok {
			old := schemas.Content[i+1]
			end := len(lines) - 1
			if i+2 < len(schemas.Content) {
				end = schemas.Content[i+2].Line - 1
			}
			for _, s := range openplatform.Specs() {
				if s.Name == name {
					n := node(s.InputSchema)
					n.Line = old.Line
					if err := addPatch(n, end, 6); err != nil {
						return nil, err
					}
				}
			}
		}
	}
	sort.Slice(patches, func(i, j int) bool { return patches[i].start > patches[j].start })
	for _, p := range patches {
		lines = append(lines[:p.start], append([]string{p.text}, lines[p.end:]...)...)
	}
	return syncSupplement([]byte(strings.Join(lines, "\n")))
}
